//! Compiles the e-mail texts into the binary.
//!
//! They live next to the UI's translations, one folder per language
//! (`web/src/locales/<language>/email.json`). The list of languages is whatever folders exist
//! there, so adding a language to the platform needs no change in the server.

use std::fmt::Write;
use std::path::PathBuf;

fn main() {
    let manifest_dir = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let locales = manifest_dir.join("../../web/src/locales");
    println!("cargo:rerun-if-changed={}", locales.display());

    let mut languages: Vec<String> = std::fs::read_dir(&locales)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", locales.display()))
        .filter_map(|entry| entry.ok())
        .filter(|entry| entry.path().join("email.json").is_file())
        .map(|entry| entry.file_name().to_string_lossy().into_owned())
        .collect();
    languages.sort();
    assert!(languages.iter().any(|l| l == "en"), "the default language (en) must have an email.json");

    let mut code = String::from("/// (language, content of its email.json), generated by build.rs.\n");
    code.push_str("pub const EMAIL_LOCALES: &[(&str, &str)] = &[\n");
    for language in &languages {
        let path = locales.join(language).join("email.json").canonicalize().unwrap();
        println!("cargo:rerun-if-changed={}", path.display());
        writeln!(code, "    ({language:?}, include_str!({:?})),", path.display().to_string()).unwrap();
    }
    code.push_str("];\n");
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("email_locales.rs");
    std::fs::write(out, code).unwrap();
}
