#!/usr/bin/env bash
# Prepares spike/work/: secrets (.env), certificates (root CA, intermediate signing CA,
# server certificate, admin certificate) and CoreConfig.xml.
# Idempotent: nothing that already exists is regenerated. `--render` only rewrites
# CoreConfig.xml (after editing .env, for example LDAP_UPDATE_INTERVAL).
. "$(dirname "$0")/lib.sh"

ENV_FILE="$WORK_DIR/.env"
TAK_DIR="$WORK_DIR/tak"
INT_CA_NAME="tak-spike-intermediate"
mkdir -p "$TAK_DIR/certs" "$TAK_DIR/logs" "$WORK_DIR/logs"

rand() { LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c "${1:-24}" || true; }

if [ ! -f "$ENV_FILE" ]; then
  log "Generating $ENV_FILE"
  cat > "$ENV_FILE" <<ENVEOF
# Generated by scripts/02-init.sh — local secrets of the spike, never version this file.
LDAP_BASE_DN=dc=tak,dc=example
LDAP_ROOT_PW=$(rand)
LDAP_TAKSERVER_PW=$(rand)
LDAP_MANAGER_PW=$(rand)
# Password shared by the sample users (alice, bob, ...)
TAK_USER_PW=$(rand)
TAK_DB_PASSWORD=$(rand)
# Keystore password (CAPASS/PASS of the ZIP's certificate scripts)
TAK_CERT_PASSWORD=$(rand)
# How often TAK Server re-reads LDAP groups, in seconds
LDAP_UPDATE_INTERVAL=30
# x509useGroupCacheRequiresExtKeyUsage
REQUIRES_EKU=true
INT_CA_NAME=$INT_CA_NAME
ENVEOF
  chmod 600 "$ENV_FILE"
fi
# `docker compose up` run from spike/ reads spike/.env (git-ignored)
ln -sfn work/.env "$SPIKE_DIR/.env"
load_env

render() {
  log "Rendering $TAK_DIR/CoreConfig.xml"
  sed -e "s|__LDAP_BASE_DN__|$LDAP_BASE_DN|g" \
      -e "s|__LDAP_TAKSERVER_PW__|$LDAP_TAKSERVER_PW|g" \
      -e "s|__LDAP_UPDATE_INTERVAL__|$LDAP_UPDATE_INTERVAL|g" \
      -e "s|__REQUIRES_EKU__|$REQUIRES_EKU|g" \
      -e "s|__DB_PASSWORD__|$TAK_DB_PASSWORD|g" \
      -e "s|__CERT_PASSWORD__|$TAK_CERT_PASSWORD|g" \
      -e "s|__INT_CA_NAME__|$INT_CA_NAME|g" \
      "$SPIKE_DIR/config/CoreConfig.tpl.xml" > "$TAK_DIR/CoreConfig.xml.tmp"
  # Rewrite in place: the file is bind-mounted into the container (the inode must not change)
  cat "$TAK_DIR/CoreConfig.xml.tmp" > "$TAK_DIR/CoreConfig.xml" && rm "$TAK_DIR/CoreConfig.xml.tmp"
}

if [ "${1:-}" = "--render" ]; then render; exit 0; fi

if [ ! -f "$TAK_DIR/certs/takserver.jks" ]; then
  log "Generating certificates with image $IMG_CA (tak/certs scripts of the ZIP)"
  # The certificates are generated inside the container, then copied out with `docker cp`,
  # as the ZIP's README does. No bind mount: right after a clean-up, a re-created host
  # directory can still show its old content inside a container (seen with OrbStack), and
  # on Linux the container user (uid 1001) could not write to a directory owned by the host user.
  # MOVE_CA=true: the intermediate becomes the CA that signs what follows (server, admin).
  cid=$(docker create --entrypoint bash \
    -e CAPASS="$TAK_CERT_PASSWORD" -e PASS="$TAK_CERT_PASSWORD" -e MOVE_CA=true \
    "$IMG_CA" -c "
      set -e
      ./makeRootCa.sh --ca-name \"\$CA_NAME\"
      ./makeCert.sh ca $INT_CA_NAME
      ./makeCert.sh server takserver
      ./makeCert.sh client admin
    ")
  if ! docker start -a "$cid" > "$WORK_DIR/logs/certs.log" 2>&1; then
    tail -30 "$WORK_DIR/logs/certs.log"; docker rm "$cid" > /dev/null; exit 1
  fi
  docker cp "$cid:/tak/certs/files/." "$TAK_DIR/certs/"
  docker rm "$cid" > /dev/null
  ls "$TAK_DIR/certs"
else
  echo "Certificates already present in $TAK_DIR/certs"
fi

# TAKIgniteConfig.xml: on first start, the config, messaging and api processes of the
# container each copy TAKIgniteConfig.example.xml if the file is missing; started at the
# same time, one of them loses the race and dies (FileAlreadyExistsException) while the
# container keeps running. So the file is provided before the first start.
if [ ! -f "$TAK_DIR/TAKIgniteConfig.xml" ]; then
  cp "$TAK_SRC/tak/TAKIgniteConfig.example.xml" "$TAK_DIR/TAKIgniteConfig.xml"
fi

render
echo
echo "Ready: cd $SPIKE_DIR && docker compose up -d && scripts/03-post-start.sh"
