#!/usr/bin/env bash
# Shared variables for the spike scripts. Source it: `. "$(dirname "$0")/lib.sh"`.
set -euo pipefail

SPIKE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REPO_DIR="$(cd "$SPIKE_DIR/.." && pwd)"
WORK_DIR="$SPIKE_DIR/work"

TAK_VERSION="5.8-RELEASE-103"
TAK_ZIP="${TAK_ZIP:-$REPO_DIR/takserver-docker-hardened-$TAK_VERSION.zip}"
TAK_SRC="$WORK_DIR/takserver-docker-hardened-$TAK_VERSION"

# Image names specific to the spike, so they can be removed without touching anything else.
IMG_CA="tak-spike/ca:$TAK_VERSION"
IMG_TAK="tak-spike/takserver:$TAK_VERSION"
IMG_DB="tak-spike/takserver-db:$TAK_VERSION"

log() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

# Loads spike/work/.env (secrets generated by 02-init.sh) if present.
load_env() {
  if [ -f "$WORK_DIR/.env" ]; then
    set -a
    # shellcheck disable=SC1091
    . "$WORK_DIR/.env"
    set +a
  else
    echo "spike/work/.env is missing: run scripts/02-init.sh first" >&2
    exit 1
  fi
}

compose() { docker compose --project-directory "$SPIKE_DIR" --env-file "$WORK_DIR/.env" "$@"; }
